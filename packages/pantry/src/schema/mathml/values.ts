/**
 * The 67 MathML attribute families, derived: which `(kind, attribute)` pairs share one value type,
 * what each family is called, and which class of value type (spec 4.6) types its column. This is
 * data only. It declares no relation, roster, pattern or contract and imports nothing, so the
 * later slices that do (p6-11 to p6-16) read their names and members from here and never restate
 * them.
 *
 * Every MathML attribute value is a row of one family relation, and the family a pair belongs to
 * is fixed by its XSD type (spec 4.5), never by its element: `width` is a `length` on `m:mspace`,
 * an `mpadded-length` on `m:mpadded` and a `table-width` on `m:mtable`.
 *
 * ## The partition
 *
 * One family per declared value type after resolving named types. `xs:anySimpleType` and
 * `xs:string` are one family, `string`. Enumerations with one member set are one family. The open
 * builtin types that serve distinct concepts split by concept: `xs:anyURI` into `href`,
 * `definition-url`, `src` (the content an `m:annotation`, `m:annotation-xml` or `m:share` stands
 * for), `embed-source` (the image `m:mglyph/@src` and `m:math/@altimg` embed) and `cdgroup`;
 * `xs:NCName` by attribute (`cd`, `name`); `xs:integer` by attribute (`position`, `shift`,
 * `scriptlevel`, `index`); `xs:positiveInteger` into `span` (`rowspan`, `columnspan`),
 * `selection` and `base` (`m:cn/@base`, which the REC types and the XSD does not). `m:interval/
 * @closure` is a four-member enumeration (`closed open open-closed closed-open`, REC C15, not
 * a string). Three kinds of pair belong to no family: `id` (183 pairs, `HtmlId`), `xref` (183,
 * `AttributeIdref`) and `m:maction/@actiontype`, the one required attribute (an arm column).
 *
 * The count is 67 families over 1,484 pairs: 27 of the XSD's value types, 1 string, 14 splits and
 * 25 enumerations.
 *
 * ## The names
 *
 * Handles are lower-kebab and at most 63 bytes. One rule per family, in this order:
 *
 * 1. The XSD's type name where it names the family's values: `length`, `color`, `mpadded-length`,
 *    `unsigned-integer`, `number`, `character`, the group-alignment lists, and for enumerations the
 *    named type that spells the member set (`linestyle`, `columnalignstyle`, `verticalalign`,
 *    `group-alignment`).
 * 2. Else the family's one attribute name (`display`, `closure`, `base`, `nargs`, `class`: the builtin
 *    `xs:NMTOKENS`, `xs:NCName`, `xs:integer`, `xs:positiveInteger` and `xs:nonNegativeInteger`
 *    serve many concepts, so they take the attribute and not the builtin).
 * 3. Else a concept name stated here: `boolean` (the twelve `true false` attributes), `embed-source`,
 *    `span`, `background` (`background`, `mathbackground`), `line-thickness` (`linethickness`,
 *    `mslinethickness`), `linestyle-list` (`columnlines`, `rowlines`), `length-list`
 *    (`columnspacing`, `rowspacing`), `indentalign-line` and `indentshift-line` (the `first` and
 *    `last` attributes of each), `definition-url` (`definitionURL` in kebab).
 *
 * Where one attribute name is declared by more than one family a family keeps the bare name only
 * if its values are that attribute's own: `linebreak` is the `m:math`, `m:mo` and `m:mstyle`
 * enumeration and `mspace-linebreak` is `m:mspace`'s, which adds `indentingnewline`; `width` is
 * three families (`length`, `mpadded-length`, `table-width`); `rowalign` is the list and
 * `verticalalign` the single value; `align` is the `m:mstack` and `m:mtable` pattern.
 *
 * `relation` is `Mathml` plus the PascalCase handle. `valueType` is what types the column: the
 * roster `Mathml<Pascal>Value` for the 25 enumerations; the pattern export `mathml<Pascal>` for
 * the 26 open types (patterns are module exports, not declared names, spec 4.5); a contract for
 * the 15 whose values a base type cannot state alone, either new, `Mathml<Pascal>Value` (13), or
 * reused, `HyperlinkUri` (`href`) and `EmbedSourceUri` (`embed-source`); and `xsString` for the
 * `string` tautology, which has no domain and is never refused. The fourteenth new contract,
 * `MathmlCbytesValue`, types the arm column `MathmlCbytes.value` and belongs to no family.
 *
 * ## Reproducing it
 *
 * `inventory.json` is the output of `derive_mathml.py` (the XSD inventory of `mathml.ts`, with
 * each attribute's type and each enumeration's members). The partition is this function over
 * every `(element, attribute, type)` of it but `id`, `xref` and a required attribute, grouping
 * pairs by the returned key; the names above are then assigned by hand, one per key.
 *
 * ```python
 * import re
 * SPLIT = {"xs:anyURI", "xs:NCName", "integer=xs:integer"}
 * EMBED = {("mglyph", "src"), ("math", "altimg")}
 * CLOSURE = frozenset({"closed", "open", "open-closed", "closed-open"})
 * def key(n, a, t):
 *     if (n, a) == ("cn", "base"): return ("split", "positive-integer=xs:positiveInteger", "base")
 *     if (n, a) == ("interval", "closure"): return ("enum", CLOSURE)
 *     if (n, a) in EMBED: return ("split", "xs:anyURI", "embed-source")
 *     if t in ("anySimpleType", "xs:string"): return ("string",)
 *     m = re.fullmatch(r"(?:[\w-]+=)?enum\[xs:token\]\{(.*)\}", t)
 *     if m: return ("enum", frozenset(m.group(1).split()))
 *     if t in SPLIT: return ("split", t, a)
 *     if t == "positive-integer=xs:positiveInteger":
 *         return ("split", t, "span" if a in ("rowspan", "columnspan") else a)
 *     return ("type", t)
 * ```
 *
 * The planner's `families.py` prints it as `families 67 {'type': 27, 'string': 1, 'split': 14,
 * 'enum': 25}` and `pairs 1484`. Kind handles are `m:` and the XSD element name, as in
 * `mathmlInventory`; the test holds the pairs against that inventory.
 */

/**
 * The class of value type that types a family's column (spec 4.6): `roster` a closed enumeration,
 * `pattern` an anchored lexical pattern, `contract` a named contract over a base type, and
 * `tautology` the string that admits everything.
 */
export type FamilyClass = "contract" | "pattern" | "roster" | "tautology";

/**
 * One `(kind, attribute)` pair: the kind handle (`m:` and the element name) and the attribute
 * name as the XSD spells it.
 */
export type FamilyPair = readonly [kind: string, attribute: string];

/**
 * One attribute family: the `MathmlValueType` handle, the relation that holds its values, the class
 * of value type, the name of what types the column, and the pairs it routes.
 */
export interface Family {
  readonly class: FamilyClass;
  readonly handle: string;
  readonly pairs: readonly FamilyPair[];
  readonly relation: string;
  readonly valueType: string;
}

