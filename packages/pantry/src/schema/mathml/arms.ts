/**
 * The MathML arms: one relation per MathML handle but `m:cbytes`, 193 in all (192 thin arms and
 * `MathmlMaction`). Decisions 51 and 77: every `NodeKind` handle has its own arm, and `Qti` mirrors
 * each `Node` row of kind `k` into `nodeArms[k]`. Inert until the composition merges it into
 * `qti.ts`. `MathmlCbytes` is declared with the attributes, not here.
 *
 * A relation is `Mathml` and the PascalCase local name (`m:annotation-xml` is
 * `MathmlAnnotationXml`, `m:semantics.ci` is `MathmlSemanticsCi`). `MathmlMaction` also holds the
 * element's `actiontype`, an `anySimpleType` written as it is. The declarations, `relations` and
 * `arms` were generated by this script, run as `pnpm exec node gen.ts` from `packages/pantry` and
 * formatted with `vp fmt` (the lint orders the keys of `relations`):
 *
 * ```ts
 * import { kinds } from "#pantry/schema/kinds/mathml.ts";
 *
 * const open = "/**";
 * const close = "*" + "/";
 * const doc = (line: string): string => `${open}\n * ${line}\n ${close}\n`;
 * const pascal = (handle: string): string =>
 *   handle
 *     .slice(2)
 *     .split(/[-.]/)
 *     .map((part) => part[0]!.toUpperCase() + part.slice(1))
 *     .join("");
 *
 * const named = kinds
 *   .filter((handle) => handle !== "m:cbytes")
 *   .map((handle) => ({ handle, name: `Mathml${pascal(handle)}` }));
 * const out = named.map(({ handle, name }) =>
 *   handle === "m:maction"
 *     ? `${doc("The `m:maction` arm, with its `actiontype`.")}export const ${name} = relation(\n  "${name}",\n  { actiontype: str.regex(patterns.xsString, patterns.xsStringFlags), id: uuid },\n  ["id"],\n);\n`
 *     : `${doc(`The \`${handle}\` arm.`)}export const ${name} = relation("${name}", { id: uuid }, ["id"]);\n`,
 * );
 * const byName = named.toSorted((a, b) => (a.name < b.name ? -1 : 1));
 * out.push(
 *   `${doc("The arms by relation name.")}export const relations = {\n${byName.map((n) => `  ${n.name},`).join("\n")}\n};\n`,
 *   `${doc("The arms by handle, as `nodeArms` keys them.")}export const arms = {\n${named
 *     .toSorted((a, b) => (a.handle < b.handle ? -1 : 1))
 *     .map((n) => `  "${n.handle}": ${n.name},`)
 *     .join("\n")}\n};\n`,
 *   `${doc("No laws of its own: the capacities name kind literals and belong to the composition.")}export const rules: readonly never[] = [];\n`,
 * );
 * process.stdout.write(out.join("\n"));
 * ```
 */
