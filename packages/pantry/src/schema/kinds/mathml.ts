/**
 * The MathML vocabulary: the 194 elements of the MathML 3 XSD that QTI imports, in the MathML
 * namespace. Inert until the composition merges it into `node.ts`, so this file imports no
 * schema module that imports it back.
 *
 * `kinds` is `m:math`, then the other names in the XSD's alphabetical order with `m:semantics.ci`
 * right after `m:semantics`: the handles of the inventory leaf, in its order. `m:semantics.ci` is
 * the `semantics` element under `m:bvar` (the XSD group `semantics-ci`), so its registry row names
 * `m:bvar` as its parent and the local name `semantics`.
 *
 * `attributes` lists the MathML attribute names no earlier vocabulary declares, in first-appearance
 * order over the leaf (the first-vocabulary rule): the leaf's names less `attributeTuples.flat()`
 * of `node.ts`. The composition re-derives it against the merged vocabularies. The three tuples
 * below were pasted from the leaf by this script, run as `pnpm exec node gen.ts` from
 * `packages/pantry` and formatted with `vp fmt`:
 *
 * ```ts
 * const have = new Set<string>(attributeTuples.flat());
 * const entries = Object.values(mathmlInventory);
 * kinds = entries.map((entry) => entry.handle);
 * attributes = [
 *   ...new Set(entries.flatMap((entry) => entry.attributes.map((a) => a.name))),
 * ].filter((name) => !have.has(name));
 * registry[entry.handle] = {
 *   attributes: entry.attributes.map((a) => a.name),
 *   local: entry.element,
 *   namespace,
 *   parent: entry.handle === "m:semantics.ci" ? Option.some("m:bvar") : Option.none(),
 * };
 * ```
 *
 * The admission rows and the `annotation-xml` set are derived by the next slice; `admission` is
 * empty here.
 */
