/**
 * The relations the migration seeds, which no role writes.
 */
const seededNames = [
  "Admission",
  "AncestryStep",
  "AttributeAdmission",
  "BindingFit",
  "MappableBaseType",
  "OperatorArity",
  "OperatorArityMax",
  "RecordBindingFit",
  "ResourceTypeOf",
  "RootOfType",
] as const;

const seeded: ReadonlySet<string> = new Set(seededNames);

type Members = typeof Qti.relations;

/**
 * The names of `Qti`'s stored relations: the members that declare fields, the rosters aside.
 */
type StoredName = {
  readonly [Name in keyof Members]: Members[Name] extends { readonly fields: unknown }
    ? Name
    : never;
}[keyof Members];

/**
 * The stored relations the migration does not seed.
 */
const writableNames = Object.entries(Qti.relations)
  .filter(([name, member]) => "fields" in member && !seeded.has(name))
  .map(([name]) => name);

// SAFETY: the names are the keys of `Qti.relations` that declare `fields`, which is `StoredName`, less the seeded ones.
// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- The invariant is the SAFETY note above.
const written = writableNames as Exclude<StoredName, (typeof seededNames)[number]>[];

